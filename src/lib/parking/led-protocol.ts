function crc16(bytes: number[]): number {
  let hi = 0xff;
  let lo = 0xff;
  for (const b of bytes) {
    const index = (lo ^ b) & 0xff;
    lo = (hi ^ CRC_HI[index]) & 0xff;
    hi = CRC_LO[index] & 0xff;
  }
  return (hi << 8) | lo;
}

let seqCounter = 0;
function nextSeq(): number {
  seqCounter = (seqCounter + 1) & 0xff;
  return seqCounter;
}

function gbkBytes(text: string): number[] {
  return Array.from(iconv.encode(text, "gbk"));
}

interface Frame {
  bytes: Uint8Array;
  hex: string;
}

function buildFrame(cmd: number, data: number[], address = LED_DEFAULT_ADDRESS, seq = nextSeq()): Frame {
  const len = data.length;
  const body = [seq & 0xff, address & 0xff, 0x00, cmd & 0xff, (len >> 8) & 0xff, len & 0xff, ...data, 0x00, 0x00];
  const crc = crc16(body);
  body[body.length - 2] = (crc >> 8) & 0xff;
  body[body.length - 1] = crc & 0xff;
  const bytes = Uint8Array.from([0xaa, 0x55, ...body, 0xaf]);
  return { bytes, hex: Buffer.from(bytes).toString("hex").toUpperCase() };
}

export interface LineMessageInput {
  line: 1 | 2 | 3 | 4;
  text: string;
  color: LedColor;
  /** undefined 或 0 ＝固定顯示（0x25，掉電保存）；>0 ＝臨時訊息（0x27），顯示秒數 1~255 */
  durationSec?: number;
  address?: number;
}

export interface EncodedLine {
  line: number;
  mode: "fixed" | "temporary";
  cmd: number;
  contentBytes: number;
  overLimit: boolean;
  frameBytes: number;
  base64: string;
  hex: string;
}

export function encodeLineMessage(input: LineMessageInput): EncodedLine {
  const content = gbkBytes(input.text);
  const overLimit = content.length > LED_MAX_CONTENT_BYTES;
  const temporary = typeof input.durationSec === "number" && input.durationSec > 0;

  const data = temporary
    ? [input.line, Math.min(255, Math.max(1, input.durationSec as number)), input.color, 0x00, ...content]
    : [input.line, input.color, 0x00, ...content];

  const cmd = temporary ? 0x27 : 0x25;
  const frame = buildFrame(cmd, data, input.address);

  return {
    line: input.line,
    mode: temporary ? "temporary" : "fixed",
    cmd,
    contentBytes: content.length,
    overLimit,
    frameBytes: frame.bytes.length,
    base64: Buffer.from(frame.bytes).toString("base64"),
    hex: frame.hex,
  };
}

/** 0x21 取消臨顯內容：lines 為要取消的行號（1-4）列表 */
export function encodeCancelTemporary(lines: number[], address?: number): EncodedLine {
  let bitmask = 0;
  for (const line of lines) {
    if (line >= 1 && line <= 4) bitmask |= 1 << (line - 1);
  }
  const frame = buildFrame(0x21, [bitmask], address);
  return {
    line: 0,
    mode: "temporary",
    cmd: 0x21,
    contentBytes: 0,
    overLimit: false,
    frameBytes: frame.bytes.length,
    base64: Buffer.from(frame.bytes).toString("base64"),
    hex: frame.hex,
  };
}
